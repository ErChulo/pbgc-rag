#!/usr/bin/env python3
"""Bundle our classic parsers into an offline Blob-worker source asset.

Development only. No source document, dependency download or parser executes.
Run --check to detect stale generated content after parser edits.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'vendor' / 'ingest-worker-source.js'
ADAPTER = ROOT / 'assets' / 'ingest.js'
REQUIRED = ('assets/core.js', 'assets/formats.js')
OPTIONAL = ('assets/legacy.js', 'assets/sqlite.js', 'assets/templates.js')
BOOTSTRAP = r"""
'use strict';
self.onmessage = async function (event) {
  const data = event.data;
  if (!data || !['parse','render-template'].includes(data.type) || typeof data.requestId !== 'string') return;
  const requestId = data.requestId;
  try {
    if (data.type==='parse' && typeof data.name !== 'string' || !(data.bytes instanceof ArrayBuffer)) throw Error('Invalid isolated parser request.');
    const bytes = new Uint8Array(data.bytes);
    const maxInputBytes=data.maxInputBytes??5*1024*1024;
    if(!Number.isSafeInteger(maxInputBytes)||maxInputBytes<5*1024*1024||maxInputBytes>64*1024*1024)throw Error('Source input budget must be between 5 and 64 MiB.');
    if (bytes.length > maxInputBytes) throw Error('Source exceeds its configured input byte budget.');
    if(data.type==='render-template'){
      if(typeof PBGCRag.renderTemplate!=='function')throw Error('Template renderer is unavailable in this worker build.');
      const result=await PBGCRag.renderTemplate(bytes,data.manifest,data.values);
      self.postMessage({type:'template-result',requestId,result},[result.bytes.buffer]);return;
    }
    const ext = data.name.toLowerCase().split('.').pop();
    let result;
    if (ext === 'doc' || ext === 'xls') {
      if (typeof PBGCRag.parseLegacyBytes !== 'function') throw Error('Legacy parser is unavailable in this worker build.');
      result = await PBGCRag.parseLegacyBytes(data.name, bytes);
    } else if (ext === 'sqlite' || ext === 'sqlite3' || ext === 'db') {
      if (typeof PBGCRag.parseSqliteBytes !== 'function') throw Error('SQLite parser is unavailable in this worker build.');
      result = await PBGCRag.parseSqliteBytes(bytes);
    } else result = await PBGCRag.parseBytes(data.name, bytes,{maxInputBytes});
    self.postMessage({type:'result',requestId,result});
  } catch (error) {
    self.postMessage({type:'error',requestId,message:error && typeof error.message === 'string' ? error.message : 'Isolated parser failed.'});
  }
};
"""


def generated():
    paths = REQUIRED + tuple(path for path in OPTIONAL if (ROOT / path).exists())
    pieces = []
    inventory = []
    for path in paths:
        data = (ROOT / path).read_text(encoding='utf-8')
        inventory.append(path + ' sha256=' + hashlib.sha256(data.encode()).hexdigest())
        pieces.append('\n/* Bundled ' + path + ' */\n' + data + '\n;\n')
    deny_network = "'use strict';\nfor (const capability of ['fetch','XMLHttpRequest','WebSocket','EventSource','importScripts','Worker']) { Object.defineProperty(self, capability, {value:function () { throw Error('Network and external code loading are disabled in the ingest worker.'); }, writable:false, configurable:false}); }\n"
    source = deny_network + ''.join(pieces) + BOOTSTRAP
    header = '/* Generated by tools/build-ingest-worker.py. Do not edit.\n' + '\n'.join(inventory) + '\n*/\n'
    output = header + "'use strict';\nglobalThis.PBGCRagIngestWorkerSource = " + json.dumps(source, ensure_ascii=True) + ';\n'
    adapter = ADAPTER.read_text(encoding='utf-8')
    pinned, count = re.subn(r"const INGEST_WORKER_SHA256='[a-f0-9]{64}';",
                          "const INGEST_WORKER_SHA256='" + hashlib.sha256(source.encode('utf-8')).hexdigest() + "';", adapter)
    if count != 1:
        raise ValueError('Ingest adapter must contain exactly one worker integrity pin.')
    return output, adapter, pinned


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, adapter, pinned = generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content or adapter != pinned:
            print('Ingest worker source or runtime integrity pin is stale; run python tools/build-ingest-worker.py.', file=sys.stderr)
            return 1
        print('Ingest worker source and runtime integrity pin are current.')
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    ADAPTER.write_text(pinned, encoding='utf-8', newline='\n')
    print('Generated ' + str(OUTPUT.relative_to(ROOT)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
