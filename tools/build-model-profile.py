#!/usr/bin/env python3
"""Build the local classic-script model profile from its pinned manifest."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'vendor/local-llm/bundled.manifest.json'
TARGET = ROOT / 'assets/model-profile.js'


def generated_profile():
    manifest = json.loads(SOURCE.read_text(encoding='utf-8'))
    if (manifest.get('schemaVersion') != 1
            or not isinstance(manifest.get('id'), str)
            or not re.fullmatch(r'[-a-zA-Z0-9_.]{1,100}', manifest['id'])
            or not isinstance(manifest.get('name'), str)
            or not manifest['name'].strip() or len(manifest['name']) > 160
            or not isinstance(manifest.get('license'), str)
            or not manifest['license'].strip() or len(manifest['license']) > 80
            or not isinstance(manifest.get('source'), str)
            or not manifest['source'].startswith('https://') or len(manifest['source']) > 500
            or manifest.get('chatTemplate') not in {'chatml', 'plain'}
            or not isinstance(manifest.get('files'), list) or len(manifest['files']) != 1):
        raise ValueError('Bundled model manifest metadata is invalid')
    spec = manifest['files'][0]
    if (not isinstance(spec, dict) or not isinstance(spec.get('name'), str)
            or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]{0,159}\.gguf', spec['name'])
            or type(spec.get('bytes')) is not int or not 24 <= spec['bytes'] <= 768 * 1024 * 1024
            or not isinstance(spec.get('sha256'), str)
            or not re.fullmatch(r'[a-f0-9]{64}', spec['sha256'])):
        raise ValueError('Bundled model manifest must pin one GGUF within 768 MiB')
    value = json.dumps(manifest, ensure_ascii=True, separators=(',', ':'))
    return ("/* Generated by tools/build-model-profile.py. Do not edit by hand. */\n"
            "(function(root,factory){'use strict';const manifest=factory();"
            "if(typeof module==='object'&&module.exports)module.exports=manifest;"
            "root.PBGCRag=Object.assign(root.PBGCRag||{},{BUNDLED_MODEL:manifest});"
            "})(globalThis,function(){'use strict';const manifest=" + value + ";"
            "Object.freeze(manifest.files[0]);Object.freeze(manifest.files);"
            "return Object.freeze(manifest);});\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generated_profile()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding='utf-8') != content:
            raise SystemExit('FAIL: model profile differs from its manifest; rebuild it')
    else:
        TARGET.write_text(content, encoding='utf-8', newline='\n')
    print('PASS: bundled model profile matches its pinned manifest')


if __name__ == '__main__':
    main()
