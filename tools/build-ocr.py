#!/usr/bin/env python3
"""Build the audited classic-script offline OCR pack. Development only."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parents[1]
NPM_INTEGRITY = '1Qncm/9oKM7xgrQXZXNB+NRh19qiXGhxlrR8EwFbK5SaUbPZnS5OMtP/ghtqfd23hsr1ZvZbZjeuAGcMxd/ooA=='
LANG_SHA = '7d4322bd2a7749724879683fc3912cb542f19906c83bcc1a52132556427170b2'
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--core-tar', type=Path, required=True)
p.add_argument('--traineddata', type=Path, required=True)
p.add_argument('--check', action='store_true')
a = p.parse_args()
tar = a.core_tar.read_bytes()
if base64.b64encode(hashlib.sha512(tar).digest()).decode() != NPM_INTEGRITY:
    raise SystemExit('Tesseract npm tarball integrity differs from pinned source')
lang = a.traineddata.read_bytes()
if hashlib.sha256(lang).hexdigest() != LANG_SHA:
    raise SystemExit('English traineddata differs from pinned source')
with tarfile.open(fileobj=io.BytesIO(tar), mode='r:gz') as package:
    glue = package.extractfile('package/tesseract-core-lstm.js').read()
    wasm = package.extractfile('package/tesseract-core-lstm.wasm').read()
# The Emscripten file loader remains unreachable because wasmBinary is supplied.
# Replace every browser network call too, so accidental binary-loader fallback fails closed.
core = glue.decode().replace('fetch(', 'pbgcDeniedNetwork(').replace('new XMLHttpRequest', 'new PbgcDeniedNetworkRequest')
core = 'function pbgcDeniedNetwork(){throw Error("OCR runtime network is disabled");} function PbgcDeniedNetworkRequest(){throw Error("OCR runtime network is disabled");}\n' + core
manifest = {
 'schemaVersion':1,'kind':'offline-ocr-pack','id':'tesseract-core-6.0.0-eng-fast-4.1.0-7d4322bd2a774972',
 'runtime':'tesseract.js-core','runtimeVersion':'6.0.0','license':'Apache-2.0','language':'eng',
 'coreSource':'https://registry.npmjs.org/tesseract.js-core/-/tesseract.js-core-6.0.0.tgz',
 'npmIntegrity':'sha512-'+NPM_INTEGRITY,
 'traineddataSource':'https://raw.githubusercontent.com/tesseract-ocr/tessdata_fast/4.1.0/eng.traineddata',
 'traineddataSha256':LANG_SHA,'traineddataBytes':len(lang),'wasmSha256':hashlib.sha256(wasm).hexdigest(),'wasmBytes':len(wasm),
 'upstreamGlueSha256':hashlib.sha256(glue).hexdigest(),'patchedGlueSha256':hashlib.sha256(core.encode()).hexdigest(),
 'threads':1,'runtimeNetwork':False,'sharedMemory':False,
 'sourceRevision':'8135c61fadee753821cb6a9916e17e1309a6bbf7',
 'thirdPartyNotices':[{'path':str(path.relative_to(ROOT/'vendor/ocr')).replace('\\','/'),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()} for path in sorted((ROOT/'vendor/ocr/third-party-licenses').glob('*'))],
 'modifications':['Supply embedded WASM and English traineddata; no downloads or persistence','Replace upstream browser network calls with hard-denied functions','Run direct TessBaseAPI only in a terminable Blob worker']
}
pack = {'manifest':manifest,'coreSource':core,'wasmBase64':base64.b64encode(wasm).decode(),'languageBase64':base64.b64encode(lang).decode()}
script = '/* Apache-2.0 public OCR engine and weights. Generated by tools/build-ocr.py. */\n(function(root){"use strict";const pack='+json.dumps(pack,separators=(',',':'))+';if(typeof module==="object"&&module.exports)module.exports=pack;root.PBGCRagOcrPack=pack;})(typeof globalThis!=="undefined"?globalThis:this);\n'
manifest['packScriptSha256']=hashlib.sha256(script.encode()).hexdigest()
manifest['packScriptBytes']=len(script.encode())
output=ROOT/'vendor/ocr/ocr-pack.js'
if a.check:
 if output.read_bytes()!=script.encode():raise SystemExit('OCR pack differs from reproducible build')
else:
 output.write_text(script,encoding='utf-8')
 (ROOT/'vendor/ocr/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'status':'PASS','bytes':len(script.encode()),'manifest':manifest}))
